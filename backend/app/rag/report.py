"""Writes `corpus/build_report.md`: what the chunker and tagger did, for a person to review.

    python -m app.rag.report            # regenerate the report
    python -m app.rag.report --check    # exit 1 if the committed report is out of date

No embedding happens here, so it runs in a second with no torch install. The report is
deterministic (no timestamps), so its diff in a PR shows exactly what a corpus or
chunker change did.
"""

import argparse
import statistics
import sys
from collections import Counter
from pathlib import Path

from app.config import get_settings
from app.rag.chunker import Chunk, ChunkingResult, ChunkSettings, chunk_corpus
from app.rag.corpus import Corpus, corpus_digest, load_corpus
from app.rag.tagger import TAG_RULES, tag_chunks

REPORT_FILE = "build_report.md"
HISTOGRAM_STEP = 60


def chunking_fingerprint(corpus_dir: Path, settings: ChunkSettings) -> str:
    """Hash of the inputs that decide the chunks. `corpus_version` adds the embedding model."""
    return corpus_digest(corpus_dir, settings.fingerprint())


def build(corpus_dir: Path, settings: ChunkSettings, *, allow_unverified: bool) -> tuple[Corpus, ChunkingResult]:
    corpus = load_corpus(corpus_dir, allow_unverified=allow_unverified)
    result = chunk_corpus(corpus, settings)
    result.chunks = tag_chunks(result.chunks)
    return corpus, result


def _excerpt(text: str, n: int = 140) -> str:
    flat = " ".join(text.split()).replace("|", "\\|")
    return flat if len(flat) <= n else flat[: n - 1] + "…"


def _pct(values: list[int], q: float) -> int:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * len(ordered)))]


def render_report(corpus: Corpus, result: ChunkingResult, settings: ChunkSettings, fingerprint: str) -> str:
    chunks = result.chunks
    sizes = [c.token_count for c in chunks]
    out: list[str] = []
    w = out.append

    w("# Corpus Build Report")
    w("")
    w("Generated by `python -m app.rag.report`. **Do not edit by hand**; regenerate it and commit it with any "
      "change to `blocks.jsonl`, `documents.json` or the chunker (FAP §5.3).")
    w("")
    w(f"Chunking fingerprint: `{fingerprint}`")
    w("")

    w("## Settings")
    w("")
    w("| Setting | Value |")
    w("|---|---|")
    for key, value in settings.as_dict().items():
        w(f"| `{key}` | {value} |")
    w("| Tokenizer | `BAAI/bge-small-en-v1.5` (vendored), special tokens included, counted on `embed_text` |")
    w("")

    w("## Registry")
    w("")
    w("Every value here appears in citations. `year` and `url` must come from the published document and be "
      "checked by a person (see `corpus/README.md`).")
    w("")
    w("| `document_id` | Title | Publisher | Year | URL | Verified |")
    w("|---|---|---|---|---|---|")
    for doc_id, doc in sorted(corpus.documents.items()):
        verified = f"{doc.verified_by} ({doc.verified_on})" if doc.verified else "**no**"
        w(f"| `{doc_id}` | {doc.title} | {doc.publisher} | {doc.year or '**missing**'} | "
          f"{doc.url or '**missing**'} | {verified} |")
    w("")

    w("## Totals")
    w("")
    w("| Measure | Value |")
    w("|---|---|")
    w(f"| Documents | {len(corpus.documents)} |")
    w(f"| Blocks | {corpus.block_count} |")
    w(f"| Chunks | {len(chunks)} |")
    w(f"| Tokens per chunk: min / median / 90th percentile / max | {min(sizes)} / {int(statistics.median(sizes))} / "
      f"{_pct(sizes, 0.9)} / {max(sizes)} |")
    kinds = Counter(c.kind for c in chunks)
    w(f"| Chunk kinds | {', '.join(f'{k} {kinds[k]}' for k in ('prose', 'list', 'table', 'mixed'))} |")
    w(f"| Restricted chunks | {sum(1 for c in chunks if c.restricted_category)} |")
    w("")

    w("## Per Document")
    w("")
    w("| `document_id` | Blocks | Chunks | Min tokens | Median | Max | Pages missing |")
    w("|---|---|---|---|---|---|---|")
    for doc_id in sorted(corpus.blocks_by_doc):
        doc_chunks = [c for c in chunks if c.document_id == doc_id]
        s = [c.token_count for c in doc_chunks]
        no_page = sum(1 for b in corpus.blocks_by_doc[doc_id] if b.page is None)
        w(f"| `{doc_id}` | {len(corpus.blocks_by_doc[doc_id])} | {len(doc_chunks)} | {min(s)} | "
          f"{int(statistics.median(s))} | {max(s)} | {no_page} |")
    w("")

    w("## Size Histogram")
    w("")
    w("| Tokens | Chunks | |")
    w("|---|---|---|")
    top = settings.max_tokens
    for lo in range(0, top + 1, HISTOGRAM_STEP):
        hi = min(lo + HISTOGRAM_STEP - 1, top)
        n = sum(1 for s in sizes if lo <= s <= hi)
        w(f"| {lo}–{hi} | {n} | {'█' * n} |")
    w("")

    w("## Restricted Chunks (review these)")
    w("")
    w("A restricted chunk is declined when it is the top retrieval hit and withheld from the model otherwise "
      "(FAP §10.3). Check that each one really is a calorie or weight target, and that nothing is missing.")
    w("")
    w("| Rule | Description |")
    w("|---|---|")
    for rule in TAG_RULES:
        w(f"| `{rule.id}` ({rule.category}, {rule.target}) | {rule.description} |")
    w("")
    restricted = [c for c in chunks if c.restricted_category]
    if restricted:
        w("| Chunk | Rule | Section | Excerpt |")
        w("|---|---|---|---|")
        for c in restricted:
            w(f"| `{c.chunk_id}` | `{c.restricted_rule_id}` | {' › '.join(c.section_path)} | {_excerpt(c.text)} |")
    else:
        w("_No chunks tagged._")
    w("")

    _events_section(out, result, "Splits", ("table_split", "list_split"),
                    "Oversize tables split by row (caption and header repeated) and list runs split between items "
                    "(lead-in repeated).")
    _events_section(out, result, "Sentence-Level Splits (flagged)", ("sentence_split",),
                    "A paragraph, table row or list item was too long on its own and was cut at sentence boundaries.")
    _events_section(out, result, "Merged Tiny Sections", ("merge",),
                    f"Sections under {settings.min_tokens} tokens merged into the next sibling under the same parent.")

    w("## Chunks Under the Minimum")
    w("")
    w(f"Chunks under {settings.min_tokens} tokens that had no sibling section to merge into. Small chunks embed "
      "with less context (FAP §5.4).")
    w("")
    small = [c for c in chunks if c.token_count < settings.min_tokens]
    if small:
        w("| Chunk | Tokens | Section | Excerpt |")
        w("|---|---|---|---|")
        for c in small:
            w(f"| `{c.chunk_id}` | {c.token_count} | {' › '.join(c.section_path)} | {_excerpt(c.text, 90)} |")
    else:
        w("_None._")
    w("")

    w("## All Chunks")
    w("")
    w("| Chunk | Kind | Tokens | Pages | Section |")
    w("|---|---|---|---|---|")
    for c in chunks:
        w(f"| `{c.chunk_id}` | {c.kind} | {c.token_count} | {_pages(c)} | {' › '.join(c.section_path)} |")
    w("")
    return "\n".join(out)


def _pages(c: Chunk) -> str:
    if c.page_start is None:
        return "–"
    return str(c.page_start) if c.page_start == c.page_end else f"{c.page_start}–{c.page_end}"


def _events_section(out: list[str], result: ChunkingResult, title: str, kinds: tuple[str, ...], intro: str) -> None:
    events = [e for e in result.events if e.kind in kinds]
    out += [f"## {title}", "", intro, ""]
    if not events:
        out += ["_None._", ""]
        return
    out += ["| Document | Event | Chunks |", "|---|---|---|"]
    for e in events:
        ids = ", ".join(f"`{i}`" for i in e.chunk_ids) or "–"
        out.append(f"| `{e.document_id}` | {e.detail} | {ids} |")
    out.append("")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write corpus/build_report.md")
    parser.add_argument("--check", action="store_true", help="fail if the committed report is out of date")
    args = parser.parse_args(argv)

    app_settings = get_settings()
    corpus_dir = Path(app_settings.CORPUS_DIR)
    settings = ChunkSettings.from_settings(app_settings)
    # The report is a review tool, so it also runs before the registry is verified; the index build won't.
    corpus, result = build(corpus_dir, settings, allow_unverified=True)
    report = render_report(corpus, result, settings, chunking_fingerprint(corpus_dir, settings))

    path = corpus_dir / REPORT_FILE
    if args.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != report:
            print(f"{path} is out of date: run `python -m app.rag.report` and commit it", file=sys.stderr)
            return 1
        print(f"{path} is up to date")
        return 0
    path.write_text(report, encoding="utf-8")
    print(f"wrote {path}: {len(result.chunks)} chunks, "
          f"{sum(1 for c in result.chunks if c.restricted_category)} restricted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
